/**
 * 一份思路的尺寸上限。**桌面端与 dsh 插件共用这一份数值，两端都不许自己再拍一个数。**
 *
 * 这个文件存在的理由：0930 之前两端各自硬编码过一套上限（桌面端每条 2 万字、插件每条 4 千字），
 * 于是同一份思路在不同收件端被切成不同长度，发的人和收的人都不知道内容少了一截。
 *
 * ── 两道闸，都是整份级别 ────────────────────────────────────────────────
 *
 * `IDEA_DOC_BYTES_MAX` —— 由传输链路倒推，不是拍脑袋：
 *     服务端 `MAX_BODY` 32 MB（`server/lib/router.js`）
 *   ÷ 信封里 `ct` 是 base64、膨胀 1.33
 *   = 服务端 `MAX_ONE` 22 MB 密文（`server/routes/delivery.js`）
 *   ÷ 加密本身的开销
 *   ≈ 16.5 MB 明文，留余量取 15 MB。
 *
 * `IDEA_RAW_COUNT_MAX` —— 拦的是**收件端渲染**，与传输能力无关：
 *   2 万条列表项已经接近不做虚拟滚动的上限。要再往上得先做虚拟滚动。
 *
 * ── 没有单条长度上限 ───────────────────────────────────────────────────
 *
 * 有整份上限之后，单条再长也超不过整份。单独卡单条只会在传输能力之内凭空毁掉数据。
 * 超长记录是**显示层**折叠的事（「展开全文 · N 字」），不是把字丢掉。
 *
 * ── 量法：字节，不是字符 ───────────────────────────────────────────────
 *
 * **必须按 UTF-8 字节算。** 一个汉字 3 字节，而 JS 的 `.length` 数的是 UTF-16 码元 ——
 * 用 `.length` 判 15 MB，中文用户的实际额度会变成 45 MB，直接撞穿服务端 32 MB 的门。
 *
 *   Node   `Buffer.byteLength(s, 'utf8')`
 *   浏览器 `new TextEncoder().encode(s).length`
 *
 * 15 MB 字节的实际容量：纯中文约 524 万字，纯英文约 1573 万字符。
 */

/** 一份思路序列化后的字节上限（明文，含附件）。 */
export const IDEA_DOC_BYTES_MAX = 15 * 1024 * 1024

/** 一份思路里原始记录的条数上限。 */
export const IDEA_RAW_COUNT_MAX = 20_000

/** 跨 Node 与浏览器的 UTF-8 字节数。**别用 `.length` 代替它。** */
export function utf8Bytes(s: string): number {
  return typeof Buffer !== 'undefined' ? Buffer.byteLength(s, 'utf8') : new TextEncoder().encode(s).length
}
